-- id는 식별 쉬운 고정 uuid: 유저 ...0001~0005, 워크스페이스 ...1001~1003, 스프린트 ...2001~2002

-- ===== auth 유저 (로그인 가능한 실제 계정) =====
do $$
declare
  i int;
  uid uuid;
  mail text;
begin
  for i in 1..5 loop
    uid := ('00000000-0000-0000-0000-00000000000' || i)::uuid;
    mail := 'test' || i || '@test.com';

    insert into auth.users (
      instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
      raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
      confirmation_token, recovery_token, email_change, email_change_token_new, is_sso_user
    ) values (
      '00000000-0000-0000-0000-000000000000', uid, 'authenticated', 'authenticated',
      mail, extensions.crypt('test1234!', extensions.gen_salt('bf')), now(),
      '{"provider":"email","providers":["email"]}'::jsonb,
      jsonb_build_object('real_name', '테스트유저' || i),
      now(), now(), '', '', '', '', false
    ) on conflict (id) do nothing;

    insert into auth.identities (
      id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at
    ) values (
      gen_random_uuid(), uid, uid::text,
      jsonb_build_object('sub', uid::text, 'email', mail, 'email_verified', true),
      'email', now(), now(), now()
    ) on conflict do nothing;

    insert into public.profiles (id, email, real_name)
    values (uid, mail, '테스트유저' || i)
    on conflict (id) do nothing;
  end loop;
end $$;

